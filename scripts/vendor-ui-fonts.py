"""Download OFL UI fonts for same-origin hosting; retain upstream licenses and hashes.
Run explicitly to refresh fonts. Normal builds never contact Google Fonts.
"""
import concurrent.futures
import hashlib
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/fonts'
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'

def fetch(url):
    for attempt in range(3):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=60).read()
        except Exception:
            if attempt == 2:
                raise

def main():
    previous = json.loads((OUT / 'manifest.json').read_text(encoding='utf-8')) if (OUT / 'manifest.json').exists() else []
    manifest = []
    styles = ['/* Self-hosted OFL fonts. Generated by scripts/vendor-ui-fonts.py. */']
    for family, alias, slug, weights in [('Noto Sans SC', 'GEO Sans', 'notosanssc', '100..900'), ('Roboto Mono', 'GEO Mono', 'robotomono', '100..700')]:
        folder = OUT / slug
        folder.mkdir(parents=True, exist_ok=True)
        url = 'https://fonts.googleapis.com/css2?family=' + family.replace(' ', '+') + ':wght@' + weights + '&display=block'
        css = fetch(url).decode()
        urls = list(dict.fromkeys(re.findall(r'url\((https://[^)]+)\)', css)))
        if not urls or any(not source.endswith('.woff2') for source in urls):
            raise RuntimeError('Expected WOFF2 font subsets')
        def download(pair):
            index, source = pair
            data = fetch(source)
            if data[:4] != b'wOF2':
                raise RuntimeError('Invalid WOFF2 response')
            name = f'{index:03d}-{hashlib.sha256(data).hexdigest()[:12]}.woff2'
            (folder / name).write_bytes(data)
            return {'family': family, 'source': source, 'path': f'fonts/{slug}/{name}', 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            files = list(pool.map(download, enumerate(urls)))
        for record in files:
            css = css.replace(record['source'], '/' + record['path'])
        css = css.replace("'" + family + "'", "'" + alias + "'")
        styles.append(css)
        license_url = f'https://raw.githubusercontent.com/google/fonts/main/ofl/{slug}/OFL.txt'
        (folder / 'OFL.txt').write_bytes(fetch(license_url))
        manifest.append({'family': family, 'css_source': url, 'license': license_url, 'files': files})
        print(f'{family}: {len(files)} subsets, {sum(f["bytes"] for f in files):,} bytes', flush=True)
    (ROOT / 'public/geo-fonts.css').write_text('\n'.join(styles), encoding='utf-8')
    (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    current = {f['path'] for family in manifest for f in family['files']}
    for family in previous:
        for record in family['files']:
            path = (ROOT / 'public' / record['path']).resolve()
            if record['path'] not in current and path.is_relative_to(OUT.resolve()) and path.suffix == '.woff2':
                path.unlink(missing_ok=True)

if __name__ == '__main__':
    main()
