<?php

namespace App\Services\Distribution;

/**
 * B4.3 Rewrite Rule Generator
 *
 * Generates nginx/Apache rewrite rules for GEOFlow Agent sites
 * to ensure clean URL routing for the Agent protocol endpoints.
 */
class RewriteRuleGenerator
{
    /**
     * Generate rewrite rules for a given domain and server type.
     *
     * @param  string  $domain  Target site domain
     * @param  string  $serverType  'nginx' or 'apache'
     * @param  string  $frontMode  'proxy', 'static', or 'hybrid'
     * @return array{rules: string, server_type: string, instructions: string}
     */
    public function generate(string $domain, string $serverType = 'nginx', string $frontMode = 'proxy'): array
    {
        $rules = match (strtolower($serverType)) {
            'nginx' => $this->generateNginx($domain, $frontMode),
            'apache', 'httpd' => $this->generateApache($domain, $frontMode),
            default => $this->generateNginx($domain, $frontMode),
        };

        return [
            'rules' => $rules,
            'server_type' => strtolower($serverType),
            'domain' => $domain,
            'front_mode' => $frontMode,
            'instructions' => $this->instructions($serverType, $domain),
        ];
    }

    private function generateNginx(string $domain, string $frontMode): string
    {
        $agentBlock = <<<'NGINX'
    # GEOFlow Agent protocol — always proxy to Laravel
    location /geoflow-agent/ {
        try_files $uri $uri/ /index.php?$query_string;
    }
NGINX;

        $frontBlock = match ($frontMode) {
            'static' => <<<'NGINX'

    # Static front mode — serve static files, fallback to index.html
    location / {
        try_files $uri $uri/ /index.html;
    }
NGINX,
            'hybrid' => <<<'NGINX'

    # Hybrid mode — static assets first, then Laravel
    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    # SEO: serve sitemap and llms.txt directly
    location = /sitemap.xml {
        try_files $uri /index.php?$query_string;
    }

    location = /llms.txt {
        try_files $uri /index.php?$query_string;
    }
NGINX,
            default => <<<'NGINX'

    # Proxy mode — all requests to Laravel
    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }
NGINX,
        };

        return <<<NGINX
# GEO SaaS Rewrite Rules for {$domain}
# Generated by GEO SaaS Distribution Engine

server {
    listen 80;
    server_name {$domain};
    root /var/www/{$domain}/public;
    index index.php index.html;

    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;
{$agentBlock}
{$frontBlock}

    # PHP-FPM
    location ~ \.php$ {
        fastcgi_pass unix:/var/run/php/php8.2-fpm.sock;
        fastcgi_param SCRIPT_FILENAME \$realpath_root\$fastcgi_script_name;
        include fastcgi_params;
    }

    # Deny hidden files
    location ~ /\.(?!well-known) {
        deny all;
    }
}
NGINX;
    }

    private function generateApache(string $domain, string $frontMode): string
    {
        $agentBlock = <<<'APACHE'
    # GEOFlow Agent protocol — always route to Laravel
    RewriteRule ^geoflow-agent/.*$ index.php [L,QSA]
APACHE;

        $frontBlock = match ($frontMode) {
            'static' => <<<'APACHE'

    # Static front mode
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.html [L]
APACHE,
            'hybrid' => <<<'APACHE'

    # Hybrid mode — static first, then Laravel
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.php [L,QSA]

    # SEO files
    RewriteRule ^sitemap\.xml$ index.php [L,QSA]
    RewriteRule ^llms\.txt$ index.php [L,QSA]
APACHE,
            default => <<<'APACHE'

    # Proxy mode — all to Laravel
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.php [L,QSA]
APACHE,
        };

        return <<<APACHE
# GEO SaaS Rewrite Rules for {$domain}
# Generated by GEO SaaS Distribution Engine
# Place this in your .htaccess or VirtualHost configuration

<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteBase /

{$agentBlock}
{$frontBlock}
</IfModule>

# Security headers
<IfModule mod_headers.c>
    Header always set X-Frame-Options "SAMEORIGIN"
    Header always set X-Content-Type-Options "nosniff"
    Header always set X-XSS-Protection "1; mode=block"
</IfModule>

# Deny hidden files
<FilesMatch "^\.">
    Order allow,deny
    Deny from all
</FilesMatch>
APACHE;
    }

    private function instructions(string $serverType, string $domain): string
    {
        if (strtolower($serverType) === 'apache' || strtolower($serverType) === 'httpd') {
            return <<<TEXT
Apache Rewrite Rules for {$domain}

1. Place the rules in your site's .htaccess file (in the public/ directory)
   or in the Apache VirtualHost configuration.
2. Ensure mod_rewrite is enabled: sudo a2enmod rewrite
3. Ensure AllowOverride All is set for your site directory.
4. Restart Apache: sudo systemctl restart apache2
TEXT;
        }

        return <<<TEXT
Nginx Rewrite Rules for {$domain}

1. Place the server block in /etc/nginx/sites-available/{$domain}
2. Create a symlink: sudo ln -s /etc/nginx/sites-available/{$domain} /etc/nginx/sites-enabled/
3. Test configuration: sudo nginx -t
4. Reload Nginx: sudo systemctl reload nginx
TEXT;
    }
}
