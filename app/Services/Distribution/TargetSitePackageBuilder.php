1. Download and extract the package.
2. Copy files to your Laravel project following the directory structure.
3. Set environment variables:
   GEOFLOW_AGENT_KEY_ID={$keyId}
   GEOFLOW_AGENT_SECRET={$secret}
4. The secret is shown only once. Store it securely.
