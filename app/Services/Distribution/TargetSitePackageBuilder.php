<?php

namespace App\Services\Distribution;

/**
 * B4.2 Target Site Agent Package Builder
 *
 * Generates a PHP Agent package that customers can install on their target sites
 * to implement the GEOFlow Agent protocol (health + articles endpoints).
 */
class TargetSitePackageBuilder
{
    /**
     * Generate the Agent package as a structured array of files.
     *
     * @param  string  $channelName  Human-readable channel name
     * @param  string  $keyId  The distribution channel key ID
     * @param  string  $secret  The distribution channel secret (plaintext, shown once)
     * @return array{files: array<string, string>, instructions: string}
     */
    public function build(string $channelName, string $keyId, string $secret): array
    {
        $routeFile = $this->buildRouteFile();
        $controllerFile = $this->buildControllerFile();
        $middlewareFile = $this->buildMiddlewareFile();
        $beaconMiddlewareFile = $this->buildBeaconMiddlewareFile();
        $configFile = $this->buildConfigFile($channelName, $keyId);
        $composerFile = $this->buildComposerJson();
        $readmeFile = $this->buildReadme($channelName);

        return [
            'files' => [
                'routes/geoflow-agent.php' => $routeFile,
                'app/Http/Controllers/GeoFlowAgentController.php' => $controllerFile,
                'app/Http/Middleware/VerifyGeoFlowSignature.php' => $middlewareFile,
                'app/Http/Middleware/ReportGeoFlowVisit.php' => $beaconMiddlewareFile,
                'config/geoflow-agent.php' => $configFile,
                'composer.json' => $composerFile,
                'README.md' => $readmeFile,
            ],
            'instructions' => $this->buildInstructions($channelName, $keyId, $secret),
        ];
    }

    private function buildRouteFile(): string
    {
        return <<<'PHP'
<?php

use App\Http\Controllers\GeoFlowAgentController;
use App\Http\Middleware\VerifyGeoFlowSignature;
use Illuminate\Support\Facades\Route;

/*
| GEOFlow Agent Protocol Routes
| Generated by GEO SaaS Distribution Engine
*/

Route::prefix('geoflow-agent/v1')
    ->middleware(VerifyGeoFlowSignature::class)
    ->group(function () {
        Route::get('health', [GeoFlowAgentController::class, 'health']);
        Route::post('articles', [GeoFlowAgentController::class, 'store']);
        Route::put('articles/{remoteId}', [GeoFlowAgentController::class, 'update']);
        Route::delete('articles/{remoteId}', [GeoFlowAgentController::class, 'destroy']);
    });
PHP;
    }

    private function buildControllerFile(): string
    {
        return <<<'PHP'
<?php

namespace App\Http\Controllers;

use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;

class GeoFlowAgentController extends Controller
{
    public function health(): JsonResponse
    {
        return response()->json([
            'status' => 'ok',
            'agent_version' => '1.1.0',
            'capabilities' => ['publish', 'update', 'delete', 'beacon'],
            'site_name' => config('app.name'),
        ]);
    }

    public function store(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'title' => ['required', 'string', 'max:500'],
            'slug' => ['required', 'string', 'max:255'],
            'content' => ['required', 'string'],
            'content_type' => ['nullable', 'string', 'in:html,markdown'],
            'excerpt' => ['nullable', 'string', 'max:2000'],
            'featured_image_url' => ['nullable', 'url', 'max:2000'],
            'meta' => ['nullable', 'array'],
        ]);

        $remoteId = 'geo-' . bin2hex(random_bytes(8));
        $storagePath = 'geoflow-articles/' . $remoteId . '.json';

        Storage::disk('local')->put($storagePath, json_encode(array_merge($validated, [
            'remote_id' => $remoteId,
            'status' => 'published',
            'published_at' => now()->toISOString(),
        ]), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

        $publicUrl = url('/geoflow-agent/articles/' . $remoteId);

        return response()->json([
            'status' => 'published',
            'remote_id' => $remoteId,
            'remote_url' => $publicUrl,
            'published_at' => now()->toISOString(),
        ], 201);
    }

    public function update(Request $request, string $remoteId): JsonResponse
    {
        $storagePath = 'geoflow-articles/' . $remoteId . '.json';

        if (! Storage::disk('local')->exists($storagePath)) {
            return response()->json(['error' => 'Article not found'], 404);
        }

        $validated = $request->validate([
            'title' => ['sometimes', 'string', 'max:500'],
            'content' => ['sometimes', 'string'],
            'excerpt' => ['nullable', 'string', 'max:2000'],
            'meta' => ['nullable', 'array'],
        ]);

        $existing = json_decode(Storage::disk('local')->get($storagePath), true);
        $updated = array_merge($existing, $validated, ['updated_at' => now()->toISOString()]);

        Storage::disk('local')->put($storagePath, json_encode($updated, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

        return response()->json([
            'status' => 'updated',
            'remote_id' => $remoteId,
            'updated_at' => now()->toISOString(),
        ]);
    }

    public function destroy(string $remoteId): JsonResponse
    {
        $storagePath = 'geoflow-articles/' . $remoteId . '.json';

        if (! Storage::disk('local')->exists($storagePath)) {
            return response()->json(['error' => 'Article not found'], 404);
        }

        Storage::disk('local')->delete($storagePath);

        return response()->json([
            'status' => 'deleted',
            'remote_id' => $remoteId,
        ]);
    }
}
PHP;
    }

    private function buildMiddlewareFile(): string
    {
        return <<<'PHP'
<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;

class VerifyGeoFlowSignature
{
    public function handle(Request $request, Closure $next)
    {
        $keyId = $request->header('X-GEOFlow-Key-Id');
        $timestamp = $request->header('X-GEOFlow-Timestamp');
        $nonce = $request->header('X-GEOFlow-Nonce');
        $bodyHash = $request->header('X-GEOFlow-Body-SHA256');
        $signature = $request->header('X-GEOFlow-Signature');

        if (! $keyId || ! $timestamp || ! $nonce || ! $bodyHash || ! $signature) {
            return response()->json([
                'error' => 'signature_error',
                'message' => 'Missing GEOFlow signature headers.',
            ], 401);
        }

        $maxSkew = (int) config('geoflow-agent.max_clock_skew', 300);
        if (abs(time() - (int) $timestamp) > $maxSkew) {
            return response()->json([
                'error' => 'signature_error',
                'message' => 'Request timestamp expired.',
            ], 401);
        }

        $configuredKeyId = config('geoflow-agent.key_id');
        if ($keyId !== $configuredKeyId) {
            return response()->json([
                'error' => 'signature_error',
                'message' => 'Unknown key ID.',
            ], 401);
        }

        $secret = config('geoflow-agent.secret');
        $body = $request->getContent();

        if (! hash_equals(hash('sha256', $body), $bodyHash)) {
            return response()->json([
                'error' => 'signature_error',
                'message' => 'Body hash mismatch.',
            ], 401);
        }

        $path = parse_url($request->fullUrl(), PHP_URL_PATH) ?: '/';
        $canonicalString = implode("\n", [
            strtoupper($request->method()),
            $path,
            $timestamp,
            $nonce,
            $bodyHash,
        ]);

        $expectedSignature = hash_hmac('sha256', $canonicalString, $secret);
        if (! hash_equals($expectedSignature, $signature)) {
            return response()->json([
                'error' => 'signature_error',
                'message' => 'Invalid signature.',
            ], 401);
        }

        return $next($request);
    }
}
PHP;
    }

    private function buildConfigFile(string $channelName, string $keyId): string
    {
        $escapedName = addslashes($channelName);
        $escapedKeyId = addslashes($keyId);
        // 信标默认回传当前 geo-saas 域名下的公开端点（可由 GEOFLOW_BEACON_URL 覆盖）
        $beaconUrl = rtrim(config('app.url'), '/') . '/api/geoflow-beacon/v1/visits';
        $escapedBeaconUrl = addslashes($beaconUrl);

        return <<<PHP
<?php

return [
    'channel_name' => '{$escapedName}',
    'key_id' => env('GEOFLOW_AGENT_KEY_ID', '{$escapedKeyId}'),
    'secret' => env('GEOFLOW_AGENT_SECRET', ''),
    'max_clock_skew' => 300,
    'saas_beacon_url' => env('GEOFLOW_BEACON_URL', '{$escapedBeaconUrl}'),
];
PHP;
    }

    /**
     * X3.2 采集器：terminable 中间件，响应发完后把本次访问签名为 GEOFlow 信标上报。
     * 超时 ≤2s、任何异常静默吞掉（客户站稳定性优先，信标丢了就丢了）。
     */
    private function buildBeaconMiddlewareFile(): string
    {
        return <<<'PHP'
<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;
use Illuminate\Support\Facades\Http;

class ReportGeoFlowVisit
{
    public function handle(Request $request, Closure $next): Response
    {
        return $next($request);
    }

    public function terminate(Request $request, Response $response): void
    {
        try {
            $beaconUrl = config('geoflow-agent.saas_beacon_url');
            $keyId = config('geoflow-agent.key_id');
            $secret = config('geoflow-agent.secret');
            if (! $beaconUrl || ! $keyId || ! $secret) {
                return;
            }

            $visits = [[
                'path' => $request->path(),
                'user_agent' => $request->userAgent(),
                'referer' => $request->headers->get('referer'),
                'method' => $request->method(),
                'status_code' => $response->getStatusCode(),
                'occurred_at' => now()->toISOString(),
            ]];

            $body = json_encode(['visits' => $visits]);
            $timestamp = (string) time();
            $nonce = bin2hex(random_bytes(16));
            $bodyHash = hash('sha256', $body);
            $path = parse_url($beaconUrl, PHP_URL_PATH) ?: '/';
            $canonical = implode("\n", ['POST', $path, $timestamp, $nonce, $bodyHash]);
            $signature = hash_hmac('sha256', $canonical, $secret);

            Http::withHeaders([
                'X-GEOFlow-Key-Id' => $keyId,
                'X-GEOFlow-Timestamp' => $timestamp,
                'X-GEOFlow-Nonce' => $nonce,
                'X-GEOFlow-Body-SHA256' => $bodyHash,
                'X-GEOFlow-Signature' => $signature,
            ])->withBody($body, 'application/json')
                ->timeout(2)
                ->post($beaconUrl);
        } catch (\Throwable) {
            // 客户站稳定性优先，信标丢了就丢了
        }
    }
}
PHP;
    }

    private function buildComposerJson(): string
    {
        return json_encode([
            'name' => 'geoflow/agent-package',
            'description' => 'GEOFlow Agent protocol implementation for target sites',
            'type' => 'library',
            'require' => [
                'php' => '>=8.1',
                'laravel/framework' => '>=10.0',
            ],
            'autoload' => [
                'psr-4' => [
                    'App\\Http\\Controllers\\' => 'app/Http/Controllers/',
                    'App\\Http\\Middleware\\' => 'app/Http/Middleware/',
                ],
            ],
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    }

    private function buildReadme(string $channelName): string
    {
        return <<<MD
# GEOFlow Agent Package — {$channelName}

## Installation

1. Copy the files into your Laravel project:
   - `routes/geoflow-agent.php` → your `routes/` directory
   - `app/Http/Controllers/GeoFlowAgentController.php` → your controllers
   - `app/Http/Middleware/VerifyGeoFlowSignature.php` → your middleware
   - `config/geoflow-agent.php` → your `config/` directory

2. Register the route file in `bootstrap/app.php` or `RouteServiceProvider`.

3. Set environment variables:
   ```
   GEOFLOW_AGENT_KEY_ID=<provided key ID>
   GEOFLOW_AGENT_SECRET=<provided secret>
   ```

4. Ensure `storage/app/geoflow-articles/` is writable.

## Endpoints

- `GET /geoflow-agent/v1/health` — Health check
- `POST /geoflow-agent/v1/articles` — Publish article
- `PUT /geoflow-agent/v1/articles/{remoteId}` — Update article
- `DELETE /geoflow-agent/v1/articles/{remoteId}` — Delete article

## Security

All requests are authenticated via HMAC-SHA256 signatures.
Headers: `X-GEOFlow-Key-Id`, `X-GEOFlow-Timestamp`, `X-GEOFlow-Nonce`, `X-GEOFlow-Body-SHA256`, `X-GEOFlow-Signature`.

## Optional: AI crawler visit beacon (采集二期)

The package ships `app/Http/Middleware/ReportGeoFlowVisit.php`. Mount it on the routes
that render your distributed GEO articles (terminable middleware) to report visitor hits
back to GEO SaaS — after enabling, AI crawler visits (GPTBot, etc.) show up in the GEO
analytics panel.

```php
// bootstrap/app.php 或 RouteServiceProvider 中，挂在渲染分发文章的路由组上
->middleware([\App\Http\Middleware\ReportGeoFlowVisit::class])
```

The beacon target is configured via `saas_beacon_url` in `config/geoflow-agent.php`
(defaults to the GEO SaaS domain that generated this package; override with
`GEOFLOW_BEACON_URL`). Reporting is best-effort and never blocks page rendering.
MD;
    }

